import { useState, useEffect } from 'react';
import { Droplets, Beaker, Sprout, Wind, Activity } from 'lucide-react';
import Sidebar from '../components/Sidebar';
import { API_BASE_URL, THRESHOLDS } from '../config';

const FarmerDashboard = () => {
    const [data, setData] = useState(null);
    const [loading, setLoading] = useState(true);

    useEffect(() => {
        const fetchDashboard = async () => {
            const token = sessionStorage.getItem('access_token');
            if (!token) return;
            try {
                const response = await fetch(`${API_BASE_URL}/farmer/dashboard/`, {
                    headers: { 'Authorization': `Bearer ${token}` }
                });
                if (response.status === 401) {
                    window.location.href = '/logout';
                    return;
                }
                if (response.ok) {
                    const result = await response.json();
                    setData(result);
                }
            } catch (error) {
                console.error("Error fetching dashboard:", error);
            } finally {
                setLoading(false);
            }
        };
        fetchDashboard();
        const interval = setInterval(fetchDashboard, 5000);
        return () => clearInterval(interval);
    }, []);

    const handleDownloadReport = () => {
        if (!data || !data.latest_reading) return;
        const r = data.latest_reading;
        const now = new Date().toLocaleString();
        const reportContent = [
            '====================================================',
            '         SOILSENSE — FARMER SOIL HEALTH REPORT',
            '====================================================',
            `Generated On  : ${now}`,
            `Farmer Name   : ${data.farmer_name}`,
            `Control ID    : ${data.control_id}`,
            `Barangay      : ${data.barangay}`,
            `Farm Location : ${data.farm_location}`,
            `Reading Date  : ${new Date(r.recorded_at).toLocaleString()}`,
            '----------------------------------------------------',
            'SOIL READINGS (from IoT Sensor)',
            '----------------------------------------------------',
            `Nitrogen (N)  : ${r.nitrogen} mg/kg`,
            `Phosphorus (P): ${r.phosphorus} mg/kg`,
            `Potassium (K) : ${r.potassium} mg/kg`,
            `Soil pH       : ${r.ph}`,
            `Moisture      : ${r.moisture}%`,
            '----------------------------------------------------',
            'ML CLASSIFICATION & RECOMMENDATION (Random Forest)',
            '----------------------------------------------------',
            `Soil Condition   : ${r.condition}`,
            `Fertilizer       : ${r.fertilizer_name}`,
            `Nutrient Type    : ${r.nutrient_type}`,
            `Recommended Amt  : ${r.recommended_amount_kg} kg/ha`,
            `Action Plan      : ${r.action_plan}`,
            '====================================================',
            'Note: This recommendation is generated by a Machine',
            'Learning model. Please verify with your local MAO.',
            '====================================================',
        ].join('\n');

        const blob = new Blob([reportContent], { type: 'text/plain' });
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = `SoilSense_Report_${data.control_id}_${new Date().toISOString().slice(0,10)}.txt`;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        URL.revokeObjectURL(url);
    };

    if (loading) {
        return (
            <>
                <Sidebar role="farmer" />
                <main className="content">
                    <header className="dashboard-header">
                        <div style={{ width: '100%' }}>
                            <div className="skeleton skeleton-title"></div>
                            <div className="skeleton skeleton-text skeleton-text-short"></div>
                        </div>
                    </header>
                    <div className="dashboard-stats">
                        <div className="skeleton skeleton-stat-box"></div>
                        <div className="skeleton skeleton-stat-box"></div>
                        <div className="skeleton skeleton-stat-box"></div>
                        <div className="skeleton skeleton-stat-box"></div>
                        <div className="skeleton skeleton-stat-box"></div>
                    </div>
                </main>
            </>
        );
    }

    const r = data?.latest_reading;

    if (!r) {
        return (
            <>
                <Sidebar role="farmer" />
                <main className="content">
                    <header className="dashboard-header">
                        <div>
                            <h1>{data.farm_location}</h1>
                            <p>Welcome back, <strong>{data.farmer_name}</strong> (#{data.control_id})</p>
                            <p className="crop-indicator">🌾 Current Crop: Rice</p>
                        </div>
                    </header>
                    <div style={{ textAlign: 'center', padding: '80px 20px', background: 'var(--surface)', borderRadius: 'var(--card-radius)', border: '1px solid rgba(255, 255, 255, 0.5)', marginTop: '40px' }}>
                        <Activity size={64} style={{ color: 'var(--text-light)', marginBottom: '20px', opacity: 0.5 }} />
                        <h2 style={{ color: 'var(--text-dark)', marginBottom: '12px', fontSize: '1.8rem' }}>No Sensor Data Yet</h2>
                        <p style={{ color: 'var(--text-light)', maxWidth: '450px', margin: '0 auto', fontSize: '1.1rem' }}>
                            Waiting for your IoT device to send its first reading. Please ensure the device is powered on, connected to a network, and placed in the soil.
                        </p>
                    </div>
                </main>
            </>
        );
    }

    return (
        <>
            <Sidebar role="farmer" />
            <main className="content">
                <header className="dashboard-header">
                    <div>
                        <h1>{data.farm_location}</h1>
                        <p>Welcome back, <strong>{data.farmer_name}</strong> (#{data.control_id})</p>
                        <p className="crop-indicator">🌾 Current Crop: Rice</p>
                    </div>
                    <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'flex-end', gap: '12px' }}>
                        <div className="badge" style={{ marginBottom: 0 }}>Live Monitoring</div>
                        <button className="btn-header" onClick={handleDownloadReport}>
                            ⬇ Download Report
                        </button>
                    </div>
                </header>
                <div className="dashboard-stats">
                    <div className="stat-box cursor-default select-none">
                        <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '8px' }}>
                            <Sprout size={20} color="var(--primary)" />
                            <h4 style={{ margin: 0 }}>Nitrogen (N)</h4>
                        </div>
                        <div style={{ display: 'flex', alignItems: 'baseline', gap: '6px' }}>
                            <span className={`text-3xl font-bold ${r.nitrogen < THRESHOLDS.nitrogen.low ? 'text-danger' : 'text-success'}`}>{r.nitrogen}</span>
                            <span style={{ fontSize: '0.85rem', color: 'var(--text-muted)', fontWeight: '500' }}>mg/kg</span>
                        </div>
                    </div>
                    <div className="stat-box cursor-default select-none">
                        <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '8px' }}>
                            <Sprout size={20} color="var(--primary)" />
                            <h4 style={{ margin: 0 }}>Phosphorus (P)</h4>
                        </div>
                        <div style={{ display: 'flex', alignItems: 'baseline', gap: '6px' }}>
                            <span className={`text-3xl font-bold ${r.phosphorus < THRESHOLDS.phosphorus.low ? 'text-danger' : 'text-success'}`}>{r.phosphorus}</span>
                            <span style={{ fontSize: '0.85rem', color: 'var(--text-muted)', fontWeight: '500' }}>mg/kg</span>
                        </div>
                    </div>
                    <div className="stat-box cursor-default select-none">
                        <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '8px' }}>
                            <Sprout size={20} color="var(--primary)" />
                            <h4 style={{ margin: 0 }}>Potassium (K)</h4>
                        </div>
                        <div style={{ display: 'flex', alignItems: 'baseline', gap: '6px' }}>
                            <span className={`text-3xl font-bold ${r.potassium < THRESHOLDS.potassium.low ? 'text-danger' : 'text-success'}`}>{r.potassium}</span>
                            <span style={{ fontSize: '0.85rem', color: 'var(--text-muted)', fontWeight: '500' }}>mg/kg</span>
                        </div>
                    </div>
                    <div className="stat-box cursor-default select-none">
                        <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '8px' }}>
                            <Beaker size={20} color="var(--primary)" />
                            <h4 style={{ margin: 0 }}>Soil pH</h4>
                        </div>
                        <div style={{ display: 'flex', alignItems: 'baseline', gap: '6px' }}>
                            <span className={`text-3xl font-bold ${r.ph < THRESHOLDS.ph.low || r.ph > THRESHOLDS.ph.high ? 'text-danger' : 'text-success'}`}>{r.ph}</span>
                            <span style={{ fontSize: '0.85rem', color: 'var(--text-muted)', fontWeight: '500' }}>
                                ({r.ph < THRESHOLDS.ph.low ? 'Acidic' : (r.ph > THRESHOLDS.ph.high ? 'Alkaline' : 'Optimal')})
                            </span>
                        </div>
                    </div>
                    <div className="stat-box cursor-default select-none">
                        <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '8px' }}>
                            <Droplets size={20} color="var(--primary)" />
                            <h4 style={{ margin: 0 }}>Moisture</h4>
                        </div>
                        <div style={{ display: 'flex', alignItems: 'baseline', gap: '6px' }}>
                            <span className={`text-3xl font-bold ${r.moisture < THRESHOLDS.moisture.low ? 'text-warning' : 'text-success'}`}>{r.moisture}%</span>
                            <span style={{ fontSize: '0.85rem', color: 'var(--text-muted)', fontWeight: '500' }}>
                                {r.moisture < THRESHOLDS.moisture.low ? '(Low)' : '(Adequate)'}
                            </span>
                        </div>
                    </div>
                </div>

                {/* Modern Crisp Condition Status Alert */}
                <div style={{ margin: '24px 0' }}>
                    {(() => {
                        const conditionStr = r?.condition ?? 'Awaiting Data';
                        const parts = conditionStr.split(' | pH: ');
                        const soilCondition = parts[0];
                        const phLevel = parts[1] || null;
                        const isOptimal = soilCondition === 'Optimal';
                        return (
                            <div 
                                style={{
                                    background: '#ffffff',
                                    border: '1.5px solid var(--card-border)',
                                    borderLeft: `5px solid ${isOptimal ? '#047857' : '#d97706'}`,
                                    padding: '20px 24px',
                                    borderRadius: '0 16px 16px 0',
                                    boxShadow: 'var(--shadow-sm)',
                                    display: 'flex',
                                    alignItems: 'center',
                                    justifyContent: 'space-between',
                                    flexWrap: 'wrap',
                                    gap: '12px'
                                }}
                            >
                                <div>
                                    <span style={{ fontSize: '0.78rem', fontWeight: '700', textTransform: 'uppercase', letterSpacing: '0.06em', color: 'var(--text-light)' }}>
                                        Soil Health Evaluation
                                    </span>
                                    <div style={{ fontSize: '1.35rem', fontWeight: '800', color: 'var(--text-charcoal)', marginTop: '2px', letterSpacing: '-0.02em' }}>
                                        {soilCondition}
                                    </div>
                                </div>
                                {phLevel && (
                                    <span 
                                        style={{
                                            background: isOptimal ? '#ecfdf5' : '#fffbeb',
                                            color: isOptimal ? '#047857' : '#b45309',
                                            padding: '6px 14px',
                                            borderRadius: '8px',
                                            fontSize: '0.88rem',
                                            fontWeight: '700',
                                            border: `1px solid ${isOptimal ? '#a7f3d0' : '#fde68a'}`
                                        }}
                                    >
                                        pH Level: {phLevel}
                                    </span>
                                )}
                            </div>
                        );
                    })()}
                </div>

                {/* Polished Fertilizer Recommendation Card */}
                <div className="rec-card">
                    <span className="badge">Random Forest Model</span>
                    <div className="rec-header">
                        <h3>🌾 Fertilizer Recommendation</h3>
                    </div>
                    <p style={{ color: '#64748b', fontSize: '0.95rem' }}>
                        Based on your latest reading ({r?.recorded_at ? new Date(r.recorded_at).toLocaleString() : 'N/A'}):
                    </p>

                    {/* Responsive Horizontal Cards: Flex on mobile, 3-column on desktop */}
                    <div className="rec-grid">
                        <div className="rec-item-card">
                            <span className="rec-item-label">Recommended Fertilizer</span>
                            <div className="rec-item-value text-success">{r.fertilizer_name}</div>
                            <span className="rec-item-sub">ML Prediction</span>
                        </div>
                        <div className="rec-item-card">
                            <span className="rec-item-label">Nutrient Type</span>
                            <div className="rec-item-value text-warning">{r.nutrient_type}</div>
                            <span className="rec-item-sub">Deficiency Type</span>
                        </div>
                        <div className="rec-item-card">
                            <span className="rec-item-label">Amount to Apply</span>
                            <div className="rec-item-value text-danger">
                                {r.recommended_amount_kg} <span style={{ fontSize: '0.9rem', fontWeight: '500', color: '#64748b' }}>kg / ha</span>
                            </div>
                            <span className="rec-item-sub">Field Dosage</span>
                        </div>
                    </div>

                    <div className="action-list">
                        <ul>
                            <li>{r.action_plan}</li>
                        </ul>
                    </div>
                </div>
            </main>
        </>
    );
};
export default FarmerDashboard;
